-- Hand-written PostgreSQL 19 schema for the identity-explicit-writes spike (spec §3, §3.1, §4.6).
-- users is temporal through a minimal stand-in for the Norse chassis apparatus: a database-owned
-- system_period outside the EF model, a users_history table, and one BEFORE trigger that skips no-op
-- updates. The full chassis apparatus (WITHOUT OVERLAPS key, definer hardening, timeline view) is
-- deliberately not reproduced; the spike proves statement shapes, not the apparatus.

CREATE TABLE users (
	id uuid NOT NULL,
	user_name character varying(256) NOT NULL,
	email character varying(256) NOT NULL,
	email_confirmed boolean NOT NULL,
	phone_number character varying(256) NULL,
	phone_number_confirmed boolean NOT NULL,
	two_factor_enabled boolean NOT NULL,
	lockout_enabled boolean NOT NULL,
	concurrency_stamp uuid NOT NULL,
	system_period tstzrange NOT NULL,
	CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE users_history (
	id uuid NOT NULL,
	user_name character varying(256),
	email character varying(256),
	email_confirmed boolean,
	phone_number character varying(256),
	phone_number_confirmed boolean,
	two_factor_enabled boolean,
	lockout_enabled boolean,
	concurrency_stamp uuid,
	system_period tstzrange NOT NULL,
	CONSTRAINT pk_users_history PRIMARY KEY (id, system_period)
);

CREATE FUNCTION users_versioning() RETURNS trigger
LANGUAGE plpgsql AS $spike$
DECLARE ts timestamptz;
BEGIN
	IF TG_OP = 'INSERT' THEN
		NEW.system_period := tstzrange(clock_timestamp(), 'infinity');
		RETURN NEW;
	END IF;
	IF TG_OP = 'UPDATE' AND ROW(OLD.id, OLD.user_name, OLD.email, OLD.email_confirmed, OLD.phone_number, OLD.phone_number_confirmed, OLD.two_factor_enabled, OLD.lockout_enabled, OLD.concurrency_stamp)
		IS NOT DISTINCT FROM ROW(NEW.id, NEW.user_name, NEW.email, NEW.email_confirmed, NEW.phone_number, NEW.phone_number_confirmed, NEW.two_factor_enabled, NEW.lockout_enabled, NEW.concurrency_stamp) THEN
		-- No-op update: no history row, and the open version keeps its period.
		NEW.system_period := OLD.system_period;
		RETURN NEW;
	END IF;
	ts := greatest(clock_timestamp(), lower(OLD.system_period) + interval '1 microsecond');
	INSERT INTO users_history (id, user_name, email, email_confirmed, phone_number, phone_number_confirmed, two_factor_enabled, lockout_enabled, concurrency_stamp, system_period)
		VALUES (OLD.id, OLD.user_name, OLD.email, OLD.email_confirmed, OLD.phone_number, OLD.phone_number_confirmed, OLD.two_factor_enabled, OLD.lockout_enabled, OLD.concurrency_stamp, tstzrange(lower(OLD.system_period), ts));
	IF TG_OP = 'UPDATE' THEN
		NEW.system_period := tstzrange(ts, 'infinity');
		RETURN NEW;
	END IF;
	RETURN OLD;
END $spike$;

CREATE TRIGGER users_versioning BEFORE INSERT OR UPDATE OR DELETE ON users
	FOR EACH ROW EXECUTE FUNCTION users_versioning();

CREATE TABLE user_credentials (
	id uuid NOT NULL,
	password_hash bytea NULL,
	security_stamp character varying(32) NOT NULL,
	access_failed_count integer NOT NULL,
	lockout_end timestamp with time zone NULL,
	normalized_email character varying(256) NOT NULL,
	normalized_user_name character varying(256) NOT NULL,
	CONSTRAINT pk_user_credentials PRIMARY KEY (id),
	CONSTRAINT fk_user_credentials_users_id FOREIGN KEY (id) REFERENCES users (id) ON DELETE CASCADE,
	CONSTRAINT ck_user_credentials_email_is_user_name CHECK (normalized_email = normalized_user_name)
);

CREATE UNIQUE INDEX ix_user_credentials_normalized_user_name ON user_credentials (normalized_user_name);

CREATE TABLE user_claims (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	user_id uuid NOT NULL,
	claim_type character varying(256) NOT NULL,
	claim_value text NOT NULL,
	CONSTRAINT pk_user_claims PRIMARY KEY (id),
	CONSTRAINT fk_user_claims_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_tokens (
	user_id uuid NOT NULL,
	login_provider character varying(128) NOT NULL,
	name character varying(128) NOT NULL,
	value text NULL,
	CONSTRAINT pk_user_tokens PRIMARY KEY (user_id, login_provider, name),
	CONSTRAINT fk_user_tokens_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE TABLE user_passkeys (
	credential_id bytea NOT NULL,
	user_id uuid NOT NULL,
	data jsonb NOT NULL,
	CONSTRAINT pk_user_passkeys PRIMARY KEY (credential_id),
	CONSTRAINT fk_user_passkeys_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
