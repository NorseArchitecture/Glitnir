-- G6 scratch schema (PostgreSQL 19): temporal user_claims with a stored claim_value_hash, history through a
-- minimal stand-in for the chassis apparatus (chassis spec §3.1–§3.4): BEFORE INSERT/UPDATE/DELETE trigger,
-- explicit column lists, clock_timestamp() with the monotonicity clamp, WITHOUT OVERLAPS history key, and
-- the projection rule (a generated column projects into history as a plain column).
--
-- The spec §4.6 expression sha256(convert_to(claim_value, 'UTF8')) is rejected as a generation expression
-- (convert_to is STABLE); G6 proves that separately. The hash goes through an IMMUTABLE wrapper instead:
-- convert_to(text, 'UTF8') yields the same bytes for the same characters whatever the server encoding.

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE FUNCTION utf8_sha256(value text) RETURNS bytea
	LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
	RETURN pg_catalog.sha256(pg_catalog.convert_to(value, 'UTF8'));

CREATE TABLE users (
	id uuid NOT NULL,
	CONSTRAINT pk_users PRIMARY KEY (id)
);

CREATE TABLE user_claims (
	id integer GENERATED BY DEFAULT AS IDENTITY,
	user_id uuid NOT NULL,
	claim_type character varying(256) NOT NULL,
	claim_value text NOT NULL,
	claim_value_hash bytea GENERATED ALWAYS AS (utf8_sha256(claim_value)) STORED NOT NULL,
	system_period tstzrange NOT NULL,
	CONSTRAINT pk_user_claims PRIMARY KEY (id),
	CONSTRAINT fk_user_claims_users_user_id FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

CREATE UNIQUE INDEX ix_user_claims_user_id_claim_type_claim_value_hash ON user_claims (user_id, claim_type, claim_value_hash);

CREATE TABLE user_claims_history (
	id integer NOT NULL,
	user_id uuid,
	claim_type character varying(256),
	claim_value text,
	claim_value_hash bytea,
	system_period tstzrange NOT NULL,
	CONSTRAINT pk_user_claims_history PRIMARY KEY (id, system_period WITHOUT OVERLAPS)
);

CREATE FUNCTION user_claims_versioning() RETURNS trigger
LANGUAGE plpgsql AS $spike$
DECLARE ts timestamptz;
BEGIN
	IF TG_OP = 'INSERT' THEN
		NEW.system_period := tstzrange(clock_timestamp(), 'infinity');
		RETURN NEW;
	END IF;
	-- The no-op comparison names base columns only: in a BEFORE trigger NEW.claim_value_hash is NULL
	-- (stored generated columns are computed after BEFORE triggers), so including it marks every UPDATE a change.
	IF TG_OP = 'UPDATE' AND ROW(OLD.id, OLD.user_id, OLD.claim_type, OLD.claim_value)
		IS NOT DISTINCT FROM ROW(NEW.id, NEW.user_id, NEW.claim_type, NEW.claim_value) THEN
		NEW.system_period := OLD.system_period;
		RETURN NEW;
	END IF;
	ts := greatest(clock_timestamp(), lower(OLD.system_period) + interval '1 microsecond');
	-- The history copy does carry the hash: OLD.claim_value_hash is materialized, and the history column is plain.
	INSERT INTO user_claims_history (id, user_id, claim_type, claim_value, claim_value_hash, system_period)
		VALUES (OLD.id, OLD.user_id, OLD.claim_type, OLD.claim_value, OLD.claim_value_hash, tstzrange(lower(OLD.system_period), ts));
	IF TG_OP = 'UPDATE' THEN
		NEW.system_period := tstzrange(ts, 'infinity');
		RETURN NEW;
	END IF;
	RETURN OLD;
END $spike$;

CREATE TRIGGER user_claims_versioning BEFORE INSERT OR UPDATE OR DELETE ON user_claims
	FOR EACH ROW EXECUTE FUNCTION user_claims_versioning();
